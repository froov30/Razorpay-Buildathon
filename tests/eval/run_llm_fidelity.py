"""CLI: score the LLM contract compiler against the synthetic corpus.

    python -m tests.eval.run_llm_fidelity            # use cache if present
    python -m tests.eval.run_llm_fidelity --force    # recompile every contract
    python -m tests.eval.run_llm_fidelity --json     # machine-readable

Writes to ``data/synthetic/compiled_policies_llm/``, never to the committed
deterministic cache — that cache is what makes the headline metrics
reproducible with no API key, and overwriting it would silently change every
number in the README.
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import time
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()

from data.generator.contracts import build_contract_sources  # noqa: E402
from src.common.console import rule, setup_console  # noqa: E402
from src.contract_compiler.compiler import (  # noqa: E402
    ContractCompiler,
    GeminiBackend,
    LLMBackend,
    NvidiaNimBackend,
    PolicyValidationError,
)

from src.contract_compiler.dsl import Policy  # noqa: E402
from tests.eval.llm_fidelity import FidelityReport, build_report  # noqa: E402

# Contracts whose reply could not be validated into a policy, keyed by
# (contract_id, version). Populated by compile_with_llm and surfaced in the
# report: a contract the backend could not produce a usable policy for is a
# fidelity result, not an omission to be quietly dropped.
COMPILE_FAILURES: dict[tuple[str, int], str] = {}

DEFAULT_LLM_CACHE_DIR = Path("data/synthetic/compiled_policies_llm")
RESULTS_PATH = Path("data/synthetic/llm_fidelity_report.json")

FIELD_ACCURACY_BAR = 0.85
REFUSAL_ACCURACY_BAR = 0.90


BACKENDS = {"claude": LLMBackend, "gemini": GeminiBackend, "nim": NvidiaNimBackend}


def resolve_backend(name: str | None = None):
    """Pick a backend, preferring an explicit name, then whichever key exists.

    Returns an instance. Raises RuntimeError with an actionable message when no
    usable credential is present, rather than silently falling back to the
    deterministic parser — a silent fallback here would produce a "LLM fidelity"
    report generated by a regex, which is exactly the kind of quietly wrong
    number this project exists to object to.
    """
    if name:
        key = name.strip().lower()
        if key not in BACKENDS:
            raise RuntimeError(f"unknown backend {name!r}; choose from {sorted(BACKENDS)}")
        return BACKENDS[key]()

    for env_var, factory in (
        ("ANTHROPIC_API_KEY", LLMBackend),
        ("GEMINI_API_KEY", GeminiBackend),
        ("GOOGLE_API_KEY", GeminiBackend),
        ("NVIDIA_NIM_API_KEY", NvidiaNimBackend),
        ("NVIDIA_API_KEY", NvidiaNimBackend),
    ):
        if os.getenv(env_var):
            try:
                return factory()
            except RuntimeError:
                continue
    raise RuntimeError(
        "No LLM credential found. Set ANTHROPIC_API_KEY, GEMINI_API_KEY or "
        "NVIDIA_NIM_API_KEY in .env."
    )


# Google's free tier allows 5 requests per minute per model. Pacing to just
# under that is cheaper than discovering the limit by hitting it: every 429
# costs a wasted request and a ~37s forced wait, and a scored run that trips the
# limit repeatedly measures Google's rate limiter rather than the model.
FREE_TIER_MIN_INTERVAL_S = 13.0


def compile_with_llm(
    cache_dir: Path | str = DEFAULT_LLM_CACHE_DIR,
    *,
    force: bool = False,
    model: str | None = None,
    backend: str | None = None,
    min_interval_s: float = FREE_TIER_MIN_INTERVAL_S,
) -> tuple[dict[tuple[str, int], Policy], float]:
    """Compile the whole corpus through an LLM backend. Returns policies + seconds.

    Paced, not parallel. Throughput is irrelevant here — this measures accuracy
    on eleven documents, and a run that finishes in twenty seconds but trips a
    rate limit is worth less than one that takes three minutes and completes.
    """
    chosen = resolve_backend(backend)
    if model:
        chosen = type(chosen)(model=model)
    compiler = ContractCompiler(backend=chosen, cache_dir=cache_dir)
    started = time.perf_counter()
    policies: dict[tuple[str, int], Policy] = {}

    sources = build_contract_sources()
    for index, source in enumerate(sources):
        key = (source.contract_id, source.version)
        cached = compiler.cache_path(source).exists() and not force
        if index > 0 and not cached and min_interval_s > 0:
            time.sleep(min_interval_s)

        # One contract failing must not abandon the batch. Model output varies
        # between calls even at temperature 0, so a single malformed or
        # unvalidatable reply is itself a data point about reliability — losing
        # the other ten results to it would measure nothing at all.
        for attempt in range(1, 3):
            try:
                policies[key] = compiler.compile(source, force=force or attempt > 1)
                print(
                    f"  [{index + 1}/{len(sources)}] {source.contract_id} "
                    f"v{source.version}{' (cached)' if cached else ''}",
                    flush=True,
                )
                break
            except PolicyValidationError as exc:
                if attempt == 1:
                    print(
                        f"  [{index + 1}/{len(sources)}] {source.contract_id} "
                        f"v{source.version} produced an invalid policy, retrying once: "
                        f"{str(exc)[:120]}",
                        flush=True,
                    )
                    if min_interval_s > 0:
                        time.sleep(min_interval_s)
                    continue
                COMPILE_FAILURES[key] = str(exc)
                print(
                    f"  [{index + 1}/{len(sources)}] {source.contract_id} "
                    f"v{source.version} FAILED VALIDATION twice: {str(exc)[:120]}",
                    flush=True,
                )

    return policies, time.perf_counter() - started


def print_report(report: FidelityReport) -> None:
    print()
    print(rule("LLM CONTRACT COMPILER — FIDELITY", char="="))
    print(f"  Model                    : {report.model}")
    print(f"  Contracts scored         : {report.scored_contracts}")
    print(f"  Wall time                : {report.elapsed_s:.1f}s")
    print()
    print(rule("TERM EXTRACTION"))
    print(
        f"  Field accuracy           {report.field_accuracy:>20.1%}"
        f"   ({report.correct_fields}/{report.total_fields} fields)"
    )
    print(
        f"  Contracts fully correct  {report.perfect_contracts:>20}"
        f"   / {report.scored_contracts}"
    )

    failures = report.failures()
    if failures:
        print()
        print(rule("MISREAD FIELDS"))
        for f in failures:
            print(
                f"  {f.contract_id} v{f.version}  {f.field}: "
                f"expected {f.expected!r}, got {f.actual!r}"
            )

    print()
    print(rule("REFUSAL CORRECTNESS"))
    print(f"  Refusal accuracy         {report.refusal_accuracy:>20.1%}")
    for r in report.refusal_results:
        mark = "PASS" if r.passed else "FAIL"
        print(f"  [{mark}] {r.contract_id} v{r.version} ({r.expectation})")
        print(f"         {r.detail[:110]}")

    if COMPILE_FAILURES:
        print()
        print(rule("UNUSABLE REPLIES"))
        for (cid, ver), detail in sorted(COMPILE_FAILURES.items()):
            print(f"  {cid} v{ver}: {detail[:150]}")

    print()
    print(rule("VERDICT", char="="))
    ok = (
        report.field_accuracy >= FIELD_ACCURACY_BAR
        and report.refusal_accuracy >= REFUSAL_ACCURACY_BAR
    )
    print(
        f"  {'PASS' if ok else 'REVIEW'} — field {report.field_accuracy:.1%}, "
        f"refusal {report.refusal_accuracy:.1%}"
    )
    print(rule(char="="))
    print("Synthetic contracts only. No real merchant agreements.")
    print()


def main() -> int:
    setup_console()
    parser = argparse.ArgumentParser(description="Score the LLM contract compiler")
    parser.add_argument("--force", action="store_true", help="recompile, ignore cache")
    parser.add_argument("--json", action="store_true", help="emit JSON only")
    parser.add_argument("--model", default=None, help="override the model id")
    parser.add_argument(
        "--backend",
        default=None,
        choices=sorted(BACKENDS),
        help="which model backend to score (default: whichever key is present)",
    )
    parser.add_argument("--cache-dir", type=Path, default=DEFAULT_LLM_CACHE_DIR)
    args = parser.parse_args()

    logging.disable(logging.WARNING)

    policies, elapsed = compile_with_llm(
        args.cache_dir, force=args.force, model=args.model, backend=args.backend
    )
    model_name = next(
        (
            p.provenance.model
            for p in policies.values()
            if p.provenance and p.provenance.model
        ),
        "unknown",
    )
    report = build_report(policies, model=model_name, elapsed_s=elapsed)

    RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_PATH.write_text(
        json.dumps(report.to_dict(), indent=2, ensure_ascii=False), encoding="utf-8"
    )

    if args.json:
        print(json.dumps(report.to_dict(), indent=2))
    else:
        print_report(report)
        print(f"Report written to {RESULTS_PATH}")

    return (
        0
        if report.field_accuracy >= FIELD_ACCURACY_BAR
        and report.refusal_accuracy >= REFUSAL_ACCURACY_BAR
        else 1
    )


if __name__ == "__main__":
    raise SystemExit(main())
