SYNTHETIC_BANNER = (
    "SYNTHETIC DOCUMENT — generated by EntitleGraph for testing purposes.\n"
    "This is not a real merchant agreement and describes no real commercial "
    "relationship."
)


def _utc(date_str: str) -> datetime:
    return datetime.fromisoformat(date_str).replace(tzinfo=timezone.utc)


def _agreement(
    *,
    contract_id: str,
    version: int,
    seller_id: str,
    effective_line: str,
    commission: str,
    settlement: str,
    promotions: str,
    refunds: str,
    tax: str,
    delivery: str,
    preamble: str = "",
) -> str:
    return f"""{SYNTHETIC_BANNER}

MERCHANT AGREEMENT — SCHEDULE B (COMMERCIAL TERMS)

Contract: {contract_id}
Version: {version}
Seller: {seller_id}
{effective_line}
{preamble}
1. COMMISSION. {commission}

2. SETTLEMENT. {settlement}

3. PROMOTIONS. {promotions}

4. REFUNDS. {refunds}

5. TAX. {tax}

6. DELIVERY. {delivery}
"""


