"""Synthetic merchant agreement corpus.

Every document here is FABRICATED for testing. No real merchant, no real terms.

The corpus is written as prose, not as structured terms, because the contract
compiler's whole job is interpretation — handing it pre-structured data would
test nothing. Phrasing deliberately varies (the split is stated from the
platform's side in some agreements and the seller's side in others; holds appear
as words and as digits) so the compiler is not parsing one fixed template.

Four hard situations are planted on purpose (BUILD_PROMPT.md §5.1):

1. **CTR-0003** — mid-cycle rate change, seller share 70% -> 65%, amendment
   executed mid-month but stated as effective from the start of the billing
   month. Two defensible start dates. This is the required "what broke" case.
2. **CTR-0007** — overlapping promotion funding: two clauses each claim a share
   of the same discount and the shares sum to 120%. Unresolvable by arithmetic.
3. **CTR-0004** — delivery-contingent hold where the triggering event may never
   arrive, so entitlement can remain permanently un-arisen rather than late.
4. **CTR-0005** — refund precedence: commission is non-refundable *and* the
   seller payout must be clawed back before the customer is refunded, so the
   ordering of two events determines whether the ledger is correct.
"""

from __future__ import annotations

